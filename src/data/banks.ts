function buildBank(id: string, name: string, desc: string, featured: boolean, list: typeof familiarWords | typeof gaokaoWords): Bank {
  const words: WordItem[] = list.map((row, i) => {
    const [word, pos, a, b, c, d] = row as string[];
    if (featured) {
      // a=僻义 b=熟义 c=例句 d=译文
      return { id: `${id}-${i + 1}`, word, pos, meaning: a, familiar: b, example: c, exampleCn: d, bank: id };
    }
    // a=释义 b=例句 c=译文
    return { id: `${id}-${i + 1}`, word, pos, meaning: a, example: b, exampleCn: c, bank: id };
  });
  return { id, name, desc, featured, words };
}

